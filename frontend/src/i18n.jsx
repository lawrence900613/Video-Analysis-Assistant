const LangContext = createContext(null);

function resolve(obj, path) {
  return path.split(".").reduce((acc, key) => (acc == null ? undefined : acc[key]), obj);
}

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem("lang") || "en");

  useEffect(() => {
    localStorage.setItem("lang", lang);
    document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
  }, [lang]);

  const t = useCallback(
    (path, ...args) => {
      let val = resolve(translations[lang], path);
      if (val === undefined) val = resolve(translations.en, path) ?? path;
      if (typeof val === "string" && args.length === 1 && typeof args[0] === "object") {
        return val.replace(/\{(\w+)\}/g, (_, k) => args[0][k] ?? "");
      }
      return val;
    },
    [lang]
  );

  const toggle = useCallback(() => setLang((l) => (l === "zh" ? "en" : "zh")), []);

  return <LangContext.Provider value={{ lang, setLang, toggle, t }}>{children}</LangContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(LangContext);
  if (!ctx) throw new Error("useI18n must be used within LanguageProvider");
  return ctx;
}
